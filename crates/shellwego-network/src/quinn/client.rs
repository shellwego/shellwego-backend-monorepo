#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_client_new() {
        let config = QuicConfig::default();
        let client = QuinnClient::new(config);
        assert!(!client.is_connected());
    }

    #[test]
    fn test_client_not_connected() {
        let client = QuinnClient::new(QuicConfig::default());
        assert!(!client.is_connected());
    }

    #[tokio::test]
    async fn test_client_close_when_not_connected() {
        let client = QuinnClient::new(QuicConfig::default());
        // close() on a non-connected client should be a no-op
        client.close().await;
        assert!(!client.is_connected());
    }

    #[tokio::test]
    async fn test_send_when_not_connected() {
        let client = QuinnClient::new(QuicConfig::default());
        let result = client.send(Message::Heartbeat {
            node_id: uuid::Uuid::nil(),
            cpu_usage: 0.5,
            memory_usage: 0.3,
        }).await;
        // Should fail with "Not connected"
        assert!(result.is_err());
    }

    #[tokio::test]
    async fn test_receive_when_not_connected() {
        let client = QuinnClient::new(QuicConfig::default());
        let result = client.receive().await;
        // Should fail with "Not connected"
        assert!(result.is_err());
    }
}
